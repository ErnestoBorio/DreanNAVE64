def parse_charset():
    numbers = []
    for line in RAW_CHARSET_DATA.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = [p.strip() for p in line.split(',') if p.strip()]
        for p in parts:
            numbers.append(int(p))
    
    print(f"Total raw charset numbers parsed: {len(numbers)}")
    if len(numbers) < 2048:
        numbers.extend([0] * (2048 - len(numbers)))
    print(f"Final charset size after padding: {len(numbers)} bytes")
    return numbers

def generate_c_files(bytes_2048):
    # Generate src/charset_data.h
    h_content = """#ifndef CHARSET_DATA_H
#define CHARSET_DATA_H

#include <stdint.h>

#define CHARSET_SIZE 2048
#define CHARSET_NUM_CHARS 256

// Star background character definitions (Chars 0x75 to 0x7F)
#define CHAR_STAR_75 0x75
#define CHAR_STAR_76 0x76
#define CHAR_STAR_77 0x77
#define CHAR_STAR_78 0x78
#define CHAR_STAR_79 0x79
#define CHAR_STAR_7A 0x7A
#define CHAR_STAR_7B 0x7B
#define CHAR_STAR_7C 0x7C
#define CHAR_STAR_7D 0x7D
#define CHAR_STAR_7E 0x7E
#define CHAR_STAR_7F 0x7F

// Full 2048-byte rotated custom charset definition
extern const uint8_t g_custom_charset[CHARSET_SIZE];

#endif // CHARSET_DATA_H
"""
    with open("src/charset_data.h", "w") as f:
        f.write(h_content)
    print("Wrote src/charset_data.h")

    # Generate src/charset_data.c
    c_content = """#include "charset_data.h"

const uint8_t g_custom_charset[CHARSET_SIZE] = {
"""
    for ch in range(256):
        c_content += f"    // Char 0x{ch:02X} ({ch})\n"
        char_bytes = bytes_2048[ch*8 : (ch+1)*8]
        c_content += "    " + ", ".join([f"0x{b:02X}" for b in char_bytes]) + ",\n"

    c_content += "};\n"

    with open("src/charset_data.c", "w") as f:
        f.write(c_content)
    print("Wrote src/charset_data.c")

if __name__ == "__main__":
    bytes_2048 = parse_charset()
    generate_c_files(bytes_2048)
